def esc(s):
    s = str(s)
    s = s.replace("\\", "\\textbackslash{}")
    for c in "&%$#_{}":
        s = s.replace(c, "\\" + c)
    s = s.replace("<=", "$\\leq$").replace(">=", "$\\geq$").replace("->", "$\\rightarrow$")
    s = s.replace("<->", "$\\leftrightarrow$").replace("~", "\\textasciitilde{}")
    return s


def num(v, d=2, dash="--"):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return dash
    if isinstance(v, str):
        return esc(v)
    if d == 0:
        return f"{v:.0f}"
    return f"{v:.{d}f}"


def sg(x, d=2):
    return f"{0:.{d}f}" if abs(x) < 0.5 * 10 ** (-d) else f"{x:+.{d}f}"


def short_caption(c):
    """List-of-tables entry: the caption up to its first top-level ':', ';' or
    sentence end, without cross-references (long captions only)."""
    depth, paren, math, i = 0, 0, False, 0
    while i < len(c):
        ch = c[i]
        if ch == "\\":
            i += 2
            continue
        depth += {"{": 1, "}": -1}.get(ch, 0)
        paren += {"(": 1, ")": -1}.get(ch, 0)
        math ^= ch == "$"
        if depth == 0 and paren == 0 and not math and ch in ":;." and (i + 1 == len(c) or c[i + 1] == " "):
            if not re.search(r"(fig|eq|e\.g|i\.e|vs|al|No)$", c[max(0, i - 4):i]):
                break
        i += 1
    short = re.sub(r"\s*\([^()]*\\(?:cref|ref|cite)[^()]*\)", "", c[:i]).strip().rstrip(".")
    return f"[{{{short}}}]" if len(c) > 90 and short != c.strip().rstrip(".") else ""


def table(rows, header, colspec, caption, label, fname, note=None, font="\\footnotesize", longtable=False, short=None):
    """rows: list of lists of already-formatted strings."""
    lines = []
    if longtable:
        lines.append(f"{{{font}")
        lines.append(f"\\begin{{longtable}}{{{colspec}}}")
        lines.append(f"\\caption{f'[{{{short}}}]' if short else short_caption(caption)}{{{caption}}}\\label{{{label}}}\\\\")
        lines.append("\\toprule")
        lines.append(" & ".join(header) + " \\\\")
        lines.append("\\midrule\\endfirsthead")
        lines.append("\\toprule")
        lines.append(" & ".join(header) + " \\\\")
        lines.append("\\midrule\\endhead")
        lines.append("\\bottomrule\\endfoot")
        for r in rows:
            lines.append(" & ".join(r) + " \\\\")
        lines.append("\\end{longtable}}")
        if note:
            lines.append(f"\\noindent{{\\footnotesize {note}}}")
    else:
        lines.append("\\begin{table}[htbp]\\centering")
        lines.append(font)
        lines.append(f"\\caption{f'[{{{short}}}]' if short else short_caption(caption)}{{{caption}}}\\label{{{label}}}")
        lines.append(f"\\begin{{tabular}}{{{colspec}}}")
        lines.append("\\toprule")
        lines.append(" & ".join(header) + " \\\\")
        lines.append("\\midrule")
        for r in rows:
            lines.append(" & ".join(r) + " \\\\")
        lines.append("\\bottomrule")
        lines.append("\\end{tabular}")
        if note:
            lines.append(f"\\par\\smallskip\\raggedright{{\\scriptsize {note}}}")
        lines.append("\\end{table}")
    with open(os.path.join(OUT, fname), "w") as f:
        f.write("% generated by tools/make_tables.py -- do not edit by hand\n")
        f.write("\n".join(lines) + "\n")
    print("wrote", fname, len(rows), "rows")


