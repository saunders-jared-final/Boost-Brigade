#!/usr/bin/env python3
"""Generate core/params.h from a JSON parameter file (single source of truth).

    python3 gen_params.py [shuffler_params.json] [-o ../params.h]

The MATLAB twin (4_Simulink/2_SIL_Software_In_The_Loop/firmware/matlab/
export_params.m) reads the same JSON and emits the same file; keep the two
emitters in sync. Mp = M*diag(Kp_ratio) and Minv = inv(M) are computed in
double precision and rounded to float32 literals so host, ARM and the QSPICE
DLL compute identically.
"""
import argparse
import json
import math
import os
import struct
import sys

import numpy as np


def f32(x: float) -> float:
    return struct.unpack("f", struct.pack("f", x))[0]


def fmtf(x: float) -> str:
    s = "%.9g" % f32(x)
    if not any(c in s for c in ".eE"):
        s += ".0"
    return s + "f"


def sca(name: str, x: float, comment: str = "") -> str:
    c = f" /* {comment} */" if comment else ""
    return f"#define {name:<16} {fmtf(x)}{c}\n"


def mat(name: str, m: np.ndarray) -> str:
    n = m.shape[0]
    lines = [f"#define {name} {{ \\\n"]
    for i in range(n):
        row = ", ".join(fmtf(v) for v in m[i])
        tail = " }, \\\n" if i < n - 1 else " } }\n"
        lines.append("    { " + row + tail)
    return "".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument("json", nargs="?", default=os.path.join(here, "shuffler_params.json"))
    ap.add_argument("-o", "--out", default=os.path.join(here, "..", "params.h"))
    a = ap.parse_args()

    with open(a.json) as f:
        P = json.load(f)
    n_mod = int(P["n_mod"])
    n_shuf = n_mod - 1
    n_y = 2 * n_shuf
    C, S, Q = P["ctrl"], P["sup"], P["mppt"]

    M = np.array(C["M"], dtype=float)
    assert M.shape == (n_y, n_y), f"M must be {n_y}x{n_y} for n_mod={n_mod}, got {M.shape}"
    kp = np.array([C["kp_ratio_v"]] * n_shuf + [C["kp_ratio_i"]] * n_shuf)
    Mp = M @ np.diag(kp)
    Minv = np.linalg.inv(M)
    err = np.max(np.abs(Minv @ M - np.eye(n_y)))
    print(f"max |Minv*M - I| = {err:.3e}", file=sys.stderr)
    assert err < 1e-10

    ts = float(C["ts"])
    fc = float(C["fc_lpf"])
    A = (2 * math.pi * fc * ts) / (1 + 2 * math.pi * fc * ts)
    decim = round(float(S["ts"]) / ts)
    assert abs(decim * ts - float(S["ts"])) < 1e-12, "sup.ts must be an integer multiple of ctrl.ts"
    assert decim <= 255, "STACK_DECIM must fit uint8"
    mppt_n = round(float(Q["tp"]) / float(Q["ts"]))
    sup_alpha = float(S["ts"]) / float(S["tf"])

    o = []
    o.append("/*\n * params.h - power-shuffler control stack constants (GENERATED FILE)\n *\n")
    o.append(f" * Generated by ctrl_core/params/gen_params.py from {os.path.basename(a.json)}.\n")
    o.append(" * DO NOT EDIT BY HAND - edit the JSON and regenerate.\n")
    o.append(" * Mp = M*diag(Kp_ratio) and Minv = inv(M) are computed offline in DOUBLE\n")
    o.append(" * precision and rounded to float32 here; every constant is a float32 literal.\n */\n")
    o.append("#ifndef SHUFFLER_PARAMS_H\n#define SHUFFLER_PARAMS_H\n\n")
    o.append(f'#define PARAMS_VERSION "{P["version"]}"\n\n')
    o.append("/* ---------------- string topology ---------------- */\n")
    o.append(f"#define N_MOD            {n_mod} /* PV modules in the string */\n")
    o.append("#define N_SHUF           (N_MOD - 1) /* shufflers, one per adjacent module pair */\n")
    o.append("#define N_LEG            (2 * N_SHUF) /* interleaved half-bridge legs (A,B per shuffler) */\n")
    o.append("#define N_Y              (2 * N_SHUF) /* controller measurement/actuation dimension */\n\n")
    o.append(f"/* ---------------- inner controller ({ts*1e6:g} us tick) ---------------- */\n")
    o.append(sca("CTRL_TS", ts, "[s] controller period"))
    o.append(sca("CTRL_DMIN", C["dmin"], "duty clamp low"))
    o.append(sca("CTRL_DMAX", C["dmax"], "duty clamp high"))
    o.append(sca("CTRL_A", A, f"meas LPF coeff: 2*pi*fc*Ts/(1+2*pi*fc*Ts), fc = {fc:g} Hz"))
    o.append(sca("CTRL_FC_LPF", fc, "[Hz] meas LPF corner (run-time recompute of CTRL_A)"))
    o.append(sca("CTRL_KP_RATIO_V", C["kp_ratio_v"], "[s] P/I ratio, voltage channels"))
    o.append(sca("CTRL_KP_RATIO_I", C["kp_ratio_i"], "[s] P/I ratio, current channels"))
    o.append(f"\n/* plant decoupling matrix M = inv(G)*diag(kI) (row-major {n_y}x{n_y}) */\n")
    o.append(mat("CTRL_M_INIT", M))
    o.append(f"\n/* Mp = M * diag(Kp_ratio), Kp_ratio = [{C['kp_ratio_v']:g} x{n_shuf}, {C['kp_ratio_i']:g} x{n_shuf}] */\n")
    o.append(mat("CTRL_MP_INIT", Mp))
    o.append("\n/* Minv = inv(M), double-precision inverse rounded to float32 */\n")
    o.append(mat("CTRL_MINV_INIT", Minv))
    o.append("\n/* ---------------- supervisor / feasibility governor ---------------- */\n")
    o.append(sca("SUP_TS3", S["ts"], "[s] supervisor period"))
    o.append(sca("SUP_TF", S["tf"], "[s] measurement filter time constant"))
    o.append(sca("SUP_ALPHA", sup_alpha, "Ts3/TF"))
    o.append(sca("SUP_I_RATED", S["i_rated"], "[A] shuffler current rating"))
    o.append(sca("SUP_S_HI", S["s_hi"], "stress: governor engage threshold"))
    o.append(sca("SUP_S_LO", S["s_lo"], "stress: governor release threshold"))
    o.append(sca("SUP_KB", S["kb"], "[1/s] beta attack rate"))
    o.append(sca("SUP_KREL", S["krel"], "[1/s] beta release rate"))
    o.append(sca("SUP_BMAX", S["bmax"], "beta ceiling"))
    o.append(sca("SUP_RVMAX", S["rvmax"], "[V] rv clamp"))
    o.append("\n/* ---------------- MPPT, adaptive-step P&O ---------------- */\n")
    o.append(sca("MPPT_TS", Q["ts"], "[s] MPPT period"))
    o.append(sca("MPPT_TP", Q["tp"], "[s] perturb / averaging window"))
    o.append(f"#define MPPT_N           {mppt_n} /* window length = round(TP/Ts) [ticks] */\n")
    o.append(sca("MPPT_IREF0", Q["iref0"], "[A] initial string current reference"))
    o.append(sca("MPPT_IMIN", Q["imin"], "[A] Iref clamp low"))
    o.append(sca("MPPT_IMAX", Q["imax"], "[A] Iref clamp high"))
    o.append(sca("MPPT_DB", Q["db"], "[W] power deadband"))
    o.append(sca("MPPT_KA", Q["ka"], "[A/W] adaptive step gain"))
    o.append(sca("MPPT_SMIN", Q["smin"], "[A] step clamp low"))
    o.append(sca("MPPT_SMAX", Q["smax"], "[A] step clamp high"))
    o.append(sca("MPPT_S0", Q["s0"], "[A] boot perturb step"))
    o.append(sca("MPPT_BTOL", Q["btol"], "beta change tolerance (governor-active latch)"))
    o.append("\n/* ---------------- stack scheduling / interconnect ---------------- */\n")
    o.append(f"#define STACK_DECIM      {decim} /* controller ticks per supervisor/MPPT tick */\n")
    o.append(sca("STACK_RV_DLY_IC", 0.0, "rv unit-delay initial condition"))
    o.append("#define STACK_IREF_DLY_IC MPPT_IREF0 /* Iref unit-delay initial condition */\n")
    o.append("\n#endif /* SHUFFLER_PARAMS_H */\n")

    with open(a.out, "w", newline="\n") as f:
        f.write("".join(o))
    print(f"wrote {a.out} ({P['version']}, N_MOD={n_mod}, Ts={ts:g})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
