function export_params(jsonPath, outPath)
%EXPORT_PARAMS  MATLAB twin of gen_params.py: JSON parameter file -> params.h.
%   export_params()                 shuffler_params.json -> ../params.h
%   export_params(json, out)        explicit paths
%   Keep the emission in exact sync with gen_params.py (same literal format).
here = fileparts(mfilename('fullpath'));
if nargin < 1 || isempty(jsonPath), jsonPath = fullfile(here, 'shuffler_params.json'); end
if nargin < 2 || isempty(outPath),  outPath  = fullfile(here, '..', 'params.h'); end
J = jsondecode(fileread(jsonPath));
n_mod = J.n_mod;  n_shuf = n_mod - 1;  n_y = 2*n_shuf;
C = J.ctrl;  S = J.sup;  Q = J.mppt;
M = C.M;  assert(isequal(size(M), [n_y n_y]), 'M must be %dx%d', n_y, n_y);
kp = [repmat(C.kp_ratio_v,1,n_shuf), repmat(C.kp_ratio_i,1,n_shuf)];
Mp = M*diag(kp);  Minv = inv(M);
assert(max(max(abs(Minv*M - eye(n_y)))) < 1e-10, 'inv(M) sanity check failed');
ts = C.ts;  fc = C.fc_lpf;
A = 2*pi*fc*ts/(1+2*pi*fc*ts);
decim = round(S.ts/ts);  assert(abs(decim*ts - S.ts) < 1e-12 && decim <= 255);
mppt_n = round(Q.tp/Q.ts);  sup_alpha = S.ts/S.tf;

fid = fopen(outPath, 'w');  assert(fid > 0, 'cannot open %s', outPath);
cu = onCleanup(@() fclose(fid));
[~, jn, je] = fileparts(jsonPath);
fprintf(fid, '/*\n * params.h - power-shuffler control stack constants (GENERATED FILE)\n *\n');
fprintf(fid, ' * Generated by ctrl_core/params/gen_params.py from %s.\n', [jn je]);
fprintf(fid, ' * DO NOT EDIT BY HAND - edit the JSON and regenerate.\n');
fprintf(fid, ' * Mp = M*diag(Kp_ratio) and Minv = inv(M) are computed offline in DOUBLE\n');
fprintf(fid, ' * precision and rounded to float32 here; every constant is a float32 literal.\n */\n');
fprintf(fid, '#ifndef SHUFFLER_PARAMS_H\n#define SHUFFLER_PARAMS_H\n\n');
fprintf(fid, '#define PARAMS_VERSION "%s"\n\n', J.version);
fprintf(fid, '/* ---------------- string topology ---------------- */\n');
fprintf(fid, '#define N_MOD            %d /* PV modules in the string */\n', n_mod);
fprintf(fid, '#define N_SHUF           (N_MOD - 1) /* shufflers, one per adjacent module pair */\n');
fprintf(fid, '#define N_LEG            (2 * N_SHUF) /* interleaved half-bridge legs (A,B per shuffler) */\n');
fprintf(fid, '#define N_Y              (2 * N_SHUF) /* controller measurement/actuation dimension */\n\n');
fprintf(fid, '/* ---------------- inner controller (%g us tick) ---------------- */\n', ts*1e6);
sca(fid,'CTRL_TS',ts,'[s] controller period');
sca(fid,'CTRL_DMIN',C.dmin,'duty clamp low');
sca(fid,'CTRL_DMAX',C.dmax,'duty clamp high');
sca(fid,'CTRL_A',A,sprintf('meas LPF coeff: 2*pi*fc*Ts/(1+2*pi*fc*Ts), fc = %g Hz', fc));
fprintf(fid, '\n/* plant decoupling matrix M = inv(G)*diag(kI) (row-major %dx%d) */\n', n_y, n_y);
mat(fid,'CTRL_M_INIT',M);
fprintf(fid, '\n/* Mp = M * diag(Kp_ratio), Kp_ratio = [%g x%d, %g x%d] */\n', C.kp_ratio_v, n_shuf, C.kp_ratio_i, n_shuf);
mat(fid,'CTRL_MP_INIT',Mp);
fprintf(fid, '\n/* Minv = inv(M), double-precision inverse rounded to float32 */\n');
mat(fid,'CTRL_MINV_INIT',Minv);
fprintf(fid, '\n/* ---------------- supervisor / feasibility governor ---------------- */\n');
sca(fid,'SUP_TS3',S.ts,'[s] supervisor period');
sca(fid,'SUP_TF',S.tf,'[s] measurement filter time constant');
sca(fid,'SUP_ALPHA',sup_alpha,'Ts3/TF');
sca(fid,'SUP_I_RATED',S.i_rated,'[A] shuffler current rating');
sca(fid,'SUP_S_HI',S.s_hi,'stress: governor engage threshold');
sca(fid,'SUP_S_LO',S.s_lo,'stress: governor release threshold');
sca(fid,'SUP_KB',S.kb,'[1/s] beta attack rate');
sca(fid,'SUP_KREL',S.krel,'[1/s] beta release rate');
sca(fid,'SUP_BMAX',S.bmax,'beta ceiling');
sca(fid,'SUP_RVMAX',S.rvmax,'[V] rv clamp');
fprintf(fid, '\n/* ---------------- MPPT, adaptive-step P&O ---------------- */\n');
sca(fid,'MPPT_TS',Q.ts,'[s] MPPT period');
sca(fid,'MPPT_TP',Q.tp,'[s] perturb / averaging window');
fprintf(fid, '#define MPPT_N           %d /* window length = round(TP/Ts) [ticks] */\n', mppt_n);
sca(fid,'MPPT_IREF0',Q.iref0,'[A] initial string current reference');
sca(fid,'MPPT_IMIN',Q.imin,'[A] Iref clamp low');
sca(fid,'MPPT_IMAX',Q.imax,'[A] Iref clamp high');
sca(fid,'MPPT_DB',Q.db,'[W] power deadband');
sca(fid,'MPPT_KA',Q.ka,'[A/W] adaptive step gain');
sca(fid,'MPPT_SMIN',Q.smin,'[A] step clamp low');
sca(fid,'MPPT_SMAX',Q.smax,'[A] step clamp high');
sca(fid,'MPPT_S0',Q.s0,'[A] boot perturb step');
sca(fid,'MPPT_BTOL',Q.btol,'beta change tolerance (governor-active latch)');
fprintf(fid, '\n/* ---------------- stack scheduling / interconnect ---------------- */\n');
fprintf(fid, '#define STACK_DECIM      %d /* controller ticks per supervisor/MPPT tick */\n', decim);
sca(fid,'STACK_RV_DLY_IC',0,'rv unit-delay initial condition');
fprintf(fid, '#define STACK_IREF_DLY_IC MPPT_IREF0 /* Iref unit-delay initial condition */\n');
fprintf(fid, '\n#endif /* SHUFFLER_PARAMS_H */\n');
fprintf('wrote %s (%s, N_MOD=%d, Ts=%g)\n', outPath, J.version, n_mod, ts);
end

function s = fmtf(x)
s = sprintf('%.9g', double(single(x)));
if ~any(ismember(s, '.eE')), s = [s '.0']; end
s = [s 'f'];
end

function sca(fid, name, x, comment)
fprintf(fid, '#define %-16s %s /* %s */\n', name, fmtf(x), comment);
end

function mat(fid, name, m)
n = size(m,1);
fprintf(fid, '#define %s { \\\n', name);
for i = 1:n
    row = strjoin(arrayfun(@fmtf, m(i,:), 'UniformOutput', false), ', ');
    if i < n, fprintf(fid, '    { %s }, \\\n', row); else, fprintf(fid, '    { %s } }\n', row); end
end
end
