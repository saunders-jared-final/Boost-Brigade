#!/usr/bin/env python3
"""
integrate_control_v3.py - one QSPICE sheet: the hand-drawn "Buck Boost Full Bridge - v3.qsch" (parasitics as
drawn) with the firmware control stack integrated (the shuffler_ctrl_dll2 C-block of the S10 stages).

    python integrate_control_v3.py            -> ../Buck Boost Full Bridge - v3 - control.qsch

The reference file is read, never written. What the copy gets:
  * SW1 / SW2 (the fixed 50 % PULSE sources) are removed; the four half-bridge drivers take one PWM pair per leg
    (PWM_AH1/PWM_AL1 leg A of converter 1 = M3/M4, PWM_BH1/PWM_BL1 leg B = M1/M2, PWM_?H2/PWM_?L2 the same for
    converter 2 = M5/M6 and M7/M8), generated by HRTIM-style comparators: sawtooth RAMPA / RAMPB (leg B half a
    period later) against the commanded duty, dead time Tdead cut from both edges.
  * Hall sensors: the sheet's own 0 V sources V4 (A1), V7 (B1), V5 (A2), V6 (B2) sit in each winding at the
    midpoint, positive from the winding into the midpoint. TMCS1126 outputs 1.65 V + 100 mV/A (A phases) and
    1.65 V - 25 mV/A (B phases, reversed as mounted), 500 kHz output pole.
  * INA239 node voltages: the string nodes Out (PV1+), PV2P and PV3P (labels added to the drawn buses).
  * shuffler_ctrl_dll2.dll (6_RTOS/ctrl_core built with the params.h gains; copy it next to this sheet) with
    its test inputs as .params: CTRL_EN at TEN, VREF steps, KSCALE, MSEL, FILT, FC, NOISE, SAMP, KBERR, VM1SRC.
    Open loop (CTRL_EN = 0): duties D0A1 D0B1 D0A2 D0B2.
Everything new lives below the drawn circuit (y < -8000) and connects through net labels only.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "PCB_Baseline"))
from qsch_writer import Schematic, SymbolDef, sym_B, sym_V, sym_R, sym_C, p_rect, LT, GT   # noqa: E402

QDIR = os.path.normpath(os.path.join(HERE, ".."))
SRC = os.path.join(QDIR, "Buck Boost Full Bridge - v3.qsch")
DST = os.path.join(QDIR, "Buck Boost Full Bridge - v3 - control.qsch")
ENC = "latin-1"           # byte-transparent; the file's own text is cp1252 and only ASCII is added

# ----------------------------------------------------------------------------- the drawn sheet, as netlisted by QUX
# converter 1: leg A = M3/M4 (driver X6), leg B = M1/M2 (driver X7); converter 2: leg A = M5/M6 (X8), leg B = M7/M8 (X9)
PWM_RELABEL = {            # (label point) -> (old name, new name); the stub wires below each label carry the same name
    (11600, 2400): ("V_PWM1", "PWM_AH1"), (12300, 2400): ("V_PWM2", "PWM_AL1"),     # X6 PWM_H, PWM_L
    (11400, -500): ("V_PWM2", "PWM_BH1"), (12100, -500): ("V_PWM1", "PWM_BL1"),     # X7
    (-16900, -700): ("V_PWM1", "PWM_AH2"), (-16200, -700): ("V_PWM2", "PWM_AL2"),   # X8
    (-17200, -3600): ("V_PWM2", "PWM_BH2"), (-16500, -3600): ("V_PWM1", "PWM_BL2"),  # X9
}
PWM_WIRES = {(11600, 2200, 11600, 2400): "PWM_AH1", (12300, 2200, 12300, 2400): "PWM_AL1",
             (11400, -700, 11400, -500): "PWM_BH1", (12100, -700, 12100, -500): "PWM_BL1",
             (-16900, -900, -16900, -700): "PWM_AH2", (-16200, -900, -16200, -700): "PWM_AL2",
             (-17200, -3800, -17200, -3600): "PWM_BH2", (-16500, -3800, -16500, -3600): "PWM_BL2"}
SW_COMPONENTS = [(-1400, 6800), (3300, 6800)]                       # SW1, SW2
SW_WIRES = [(-1400, 6600, -1400, 6500), (-1400, 7000, -1400, 7100), (3300, 7000, 3300, 7100), (3300, 6600, 3300, 6500)]
SW_LABELS = [(-1400, 6500), (-1400, 7100), (3300, 6500), (3300, 7100)]
# string buses: QUX names them N12 (PV2+) and N10 (PV3+); the top bus is already labelled "Out"
BUS = {"N12": "PV2P", "N10": "PV3P"}
BUS_SPLIT = {"PV2P": ((-800, 100, -1700, 100), (-1200, 100), (-1200, -300), 13),
             "PV3P": ((-2100, -2900, -3000, -2900), (-2500, -2900), (-2500, -2600), 14)}
HALL = {"A1": ("V4", 0.1), "B1": ("V7", -0.025), "A2": ("V5", 0.1), "B2": ("V6", -0.025)}   # sense source, V/A

CTRL_INS = ["PV1P", "PV2P", "PV3P", "HSA1", "HSB1", "HSA2", "HSB2", "CTRL_EN", "VREF1", "VREF2",
            "KSCALE", "MSEL", "FILT", "FC", "NOISE", "SAMP", "KBERR", "FSWP", "VM1SRC", "VSTRP"]
CTRL_OUTS = ["DA1", "DB1", "DA2", "DB2", "RV1", "RV2", "BETA", "STRESS", "IM1R", "IM2R"]
CTRL_NET = {"PV1P": "Out"}          # DLL pin -> sheet net where the names differ

PARAMS = [
    ".param Tsw=5u Tdead=200n Vlogic=3.3",
    ".param TEN=1m D0A1=0.5 D0B1=0.5 D0A2=0.5 D0B2=0.5",
    ".param VSTEP1=0 VSTEP2=0 TSTEP=10m",
    ".param KSCALE=0.3 MSEL=0 FILT=0 FC=2000 NOISE=0 SAMP=1 KBERR=1 VM1SRC=0 VSTRP=0",
]
MEAS = [
    ".meas tran vd1 AVG V(Out,PV2P)-V(PV2P,PV3P) FROM 18m TO 20m",
    ".meas tran vd2 AVG V(PV2P,PV3P)-V(PV3P) FROM 18m TO 20m",
    ".meas tran ic1 AVG I(V4)-I(V7) FROM 18m TO 20m",
    ".meas tran ic2 AVG I(V5)-I(V6) FROM 18m TO 20m",
    ".meas tran ish1 AVG I(V4)+I(V7) FROM 18m TO 20m",
    ".meas tran ish2 AVG I(V5)+I(V6) FROM 18m TO 20m",
    ".meas tran da1 AVG V(DA1) FROM 18m TO 20m",
    ".meas tran db1 AVG V(DB1) FROM 18m TO 20m",
    ".meas tran da2 AVG V(DA2) FROM 18m TO 20m",
    ".meas tran db2 AVG V(DB2) FROM 18m TO 20m",
    ".meas tran pout AVG I(I1)*V(Out) FROM 18m TO 20m",
    ".meas tran stressmax MAX V(STRESS)",
]


# ----------------------------------------------------------------------------- helpers on the drawn text
def component_span(lines, x, y):
    """(start, end) line indices of the «component (x,y) ...» block, end exclusive."""
    head = f"{LT}component ({x},{y}) "
    for i, l in enumerate(lines):
        if l.strip().startswith(head):
            depth = 0
            for j in range(i, len(lines)):
                s = re.sub(r'"[^"]*"', '""', lines[j])        # quotes may hold guillemets (directive BOM)
                depth += s.count(LT) - s.count(GT)
                if depth == 0:
                    return i, j + 1
    raise KeyError(f"component at ({x},{y}) not found")


def wire_line(x1, y1, x2, y2, net):
    return f"  {LT}wire ({x1},{y1}) ({x2},{y2}) \"{net}\"{GT}"


def find_wire(lines, x1, y1, x2, y2):
    pat = re.compile(rf"\s*{LT}wire \({x1},{y1}\) \({x2},{y2}\) \"([^\"]*)\"{GT}")
    for i, l in enumerate(lines):
        if pat.match(l):
            return i
    raise KeyError(f"wire ({x1},{y1})-({x2},{y2}) not found")


def find_label(lines, x, y):
    pat = re.compile(rf"\s*{LT}net \({x},{y}\) ")
    for i, l in enumerate(lines):
        if pat.match(l):
            return i
    raise KeyError(f"label at ({x},{y}) not found")


def ctrl_sym():
    w, h = 1600, 4400
    prims = [p_rect(-w // 2, h // 2, w // 2, -h // 2, "box")]
    pins = [(n, -w // 2, h // 2 - 200 - 200 * i, 60, -40, 13, 145) for i, n in enumerate(CTRL_INS)]
    pins += [(n, w // 2, h // 2 - 200 - 200 * i, -60, -40, 14, 146) for i, n in enumerate(CTRL_OUTS)]
    pins.append(("GND", 0, -h // 2, 0, 60, 11, 147))
    return SymbolDef("shuffler_ctrl_dll2", "Ø(.DLL)", "firmware control stack (6_RTOS/ctrl_core) as a QSPICE C-block",
                     prims, pins, ref_pos=(0, h // 2 + 150), val_pos=(0, 0), extra_pos=(0, -h // 2 - 150), text_just=0)


# ----------------------------------------------------------------------------- the control block
def control_block():
    s = Schematic()
    X0, Y0 = -20000, -10000           # row 1; row 2 is 1600 lower
    Y1 = Y0 - 1600
    x = X0

    def src(sym, ref, value, net_p, net_m, xx, yy, extra=()):
        p = s.add(sym, xx, yy, ref, value, extra=extra)
        s.stub(p.pin["+"], net_p, "up", 200)
        s.stub(p.pin["-"], net_m, "down", 200)
        return p

    def two(sym, ref, value, net1, net2, xx, yy, extra=()):
        p = s.add(sym, xx, yy, ref, value, extra=extra)
        s.stub(p.pin["1"], net1, "up", 200)
        s.stub(p.pin["2"], net2, "down", 200)
        return p

    s.comment(X0, Y0 + 1900, "CONTROL (added to the v3 sheet): hall sensors -> shuffler_ctrl_dll2.dll (the firmware control stack) -> "
                             "HRTIM-style PWM comparators -> the four half-bridge drivers", size=1.3)
    s.comment(X0, Y0 + 1600, "Open loop until TEN (duties D0*), closed loop after. Test inputs are .params (right). "
                             "The DLL and ctrl_M2.txt (MSEL=2) must sit next to this .qsch. Tsw/Tdead set the PWM.")
    # hall sensors: B-source, 1k + C = 500 kHz pole (TMCS1126 output)
    s.comment(X0, Y0 + 1100, "TMCS1126 hall outputs: 1.65 V + 100 mV/A (A, into the midpoint), 1.65 V - 25 mV/A (B, reversed as mounted)")
    for ch, (vs, gain) in HALL.items():
        hs = f"HS{ch}"
        src(sym_B(), f"Bhs{ch}", f"V=1.65+({gain:g})*I({vs})", hs + "R", "GND", x, Y0)
        two(sym_R(), f"Rhs{ch}", "1k", hs + "R", hs, x + 400, Y0)
        two(sym_C(), f"Chs{ch}", "318.3p", hs, "GND", x + 800, Y0)
        x += 1300
    # ramps, enable, references
    x += 300
    s.comment(x, Y0 + 1100, "PWM ramps (leg B half a period later), controller enable, voltage-difference references")
    src(sym_V(), "Vrampa", "PULSE(0 1 0 {Tsw-2n} 1n 1n {Tsw})", "RAMPA", "GND", x, Y0); x += 700
    src(sym_V(), "Vrampb", "PULSE(0 1 {Tsw/2} {Tsw-2n} 1n 1n {Tsw})", "RAMPB", "GND", x, Y0); x += 700
    src(sym_V(), "Ven", "PWL(0 0 {TEN} 0 {TEN+1u} 1)", "CTRL_EN", "GND", x, Y0); x += 700
    src(sym_V(), "Vref1", "PWL(0 0 {TSTEP} 0 {TSTEP+1u} {VSTEP1})", "VREF1", "GND", x, Y0); x += 700
    src(sym_V(), "Vref2", "PWL(0 0 {TSTEP} 0 {TSTEP+1u} {VSTEP2})", "VREF2", "GND", x, Y0); x += 700
    # test inputs of the DLL from .params
    x += 300
    s.comment(x, Y0 + 1100, "DLL test inputs (.param): KSCALE gain scale, MSEL 0 = params.h M / 2 = ctrl_M2.txt, FILT 0 = IIR at FC, "
                            "SAMP 1 = firmware hall sampling, NOISE 1 = bench noise, KBERR, VM1SRC 0 = INA")
    for pin in CTRL_INS[10:]:
        expr = "1/Tsw" if pin == "FSWP" else pin
        src(sym_B(), f"Bt{pin}", f"V={expr}", pin, "GND", x, Y0); x += 700
    x_end = x
    # row 2: commanded duties (open loop override) and the PWM comparators
    x = X0
    s.comment(x, Y1 + 1000, "Commanded duties: the DLL output when enabled, else the open-loop duties D0*")
    for dn, d0 in (("DA1", "D0A1"), ("DB1", "D0B1"), ("DA2", "D0A2"), ("DB2", "D0B2")):
        src(sym_B(), f"Bd{dn}", f"V=if(V(CTRL_EN)>0.5, V({dn}), {d0})", dn + "C", "GND", x, Y1); x += 700
    x += 300
    s.comment(x, Y1 + 1000, "HRTIM-style comparators: top FET on while RAMP < duty - Tdead/Tsw, bottom while duty < RAMP < 1 - Tdead/Tsw "
                            "(all low at t = 0 for the operating point)")
    for k in (1, 2):
        for leg in ("A", "B"):
            dnet, ramp = f"D{leg}{k}C", f"RAMP{leg}"
            src(sym_B(), f"BpT{leg}{k}", f"V=if(time<1n, 0, if(V({ramp}) < V({dnet})-Tdead/Tsw, Vlogic, 0))",
                f"PWM_{leg}H{k}", "GND", x, Y1); x += 700
            src(sym_B(), f"BpB{leg}{k}", f"V=if(time<1n, 0, if(V({ramp}) > V({dnet}), if(V({ramp}) < 1-Tdead/Tsw, Vlogic, 0), 0))",
                f"PWM_{leg}L{k}", "GND", x, Y1); x += 700
    # the DLL, clear of both rows (its stubs reach 400 either side of the 1600-wide box)
    xd, yd = max(x, x_end) + 2000, Y0 - 1600
    p = s.add(ctrl_sym(), xd, yd, "Xc", "shuffler_ctrl_dll2", extra=("Rout=1 Cout=1p",))
    for n in CTRL_INS:
        s.stub(p.pin[n], CTRL_NET.get(n, n), "left", 400)
    for n in CTRL_OUTS:
        s.stub(p.pin[n], n, "right", 400)
    s.stub(p.pin["GND"], "GND", "down", 200)
    s.comment(xd - 800, yd + 2700, "shuffler_ctrl_dll2.dll: INA239 / hall sampling and quantisation, 10 kHz control tick, M from params.h")
    # directives (parameters, measurements) to the right of the DLL
    xt = xd + 2400
    s.comment(xt, yd + 2200, "Control parameters (edit here):")
    for i, d in enumerate(PARAMS):
        s.directive(xt, yd + 2000 - 150 * i, d)
    s.comment(xt, yd + 1200, "Measurements (settled window of the 20 ms run):")
    for i, d in enumerate(MEAS):
        s.directive(xt, yd + 1000 - 150 * i, d)
    return s


def body_lines(s):
    """The schematic's records as text lines (what Schematic.to_bytes puts between the header and the footer)."""
    out = list(s.lines)
    for (x, y, n, j) in s.labels:
        out.append(f"  {LT}net ({x},{y}) 1 {j} 0 \"{n}\"{GT}")
    for (x, y) in s._junctions():
        out.append(f"  {LT}junction ({x},{y}){GT}")
    for (x1, y1, x2, y2, n) in s.wires:
        out.append(wire_line(x1, y1, x2, y2, n))
    # directive / comment texts carry the writer's BOM placeholder: the EF BB BF bytes, as latin-1 characters
    return [l.replace("\x00BOM\x00", "\xef\xbb\xbf") for l in out]


# ----------------------------------------------------------------------------- main
def main():
    raw = open(SRC, "rb").read()
    assert raw[:4] == b"\xff\xd8\xff\xdb", "not a QSPICE schematic"
    text = raw[4:].decode(ENC)
    eol = "\r\n" if "\r\n" in text else "\n"
    lines = text.replace("\r\n", "\n").split("\n")
    while lines and lines[-1] == "":
        lines.pop()
    # 1. remove SW1 / SW2 with their wires and labels
    for (x, y) in SW_COMPONENTS:
        a, b = component_span(lines, x, y)
        del lines[a:b]
    for w in SW_WIRES:
        del lines[find_wire(lines, *w)]
    for (x, y) in SW_LABELS:
        del lines[find_label(lines, x, y)]
    # 2. one PWM pair per leg at the drivers
    for (x, y), (old, new) in PWM_RELABEL.items():
        i = find_label(lines, x, y)
        assert f'"{old}"' in lines[i], (lines[i], old)
        lines[i] = lines[i].replace(f'"{old}"', f'"{new}"')
    for (x1, y1, x2, y2), new in PWM_WIRES.items():
        i = find_wire(lines, x1, y1, x2, y2)
        lines[i] = wire_line(x1, y1, x2, y2, new)
    # 3. bus labels for the INA nodes: rename the cached wire names, split one wire per bus and hang a label stub on it
    for old, new in BUS.items():
        lines = [re.sub(rf'("\s*){old}"', rf'\g<1>{new}"', l) if l.strip().startswith(LT + "wire") and l.rstrip().endswith(f'"{old}"' + GT) else l
                 for l in lines]
        lines = [l.replace(f'"{old}"{GT}', f'"{new}"{GT}') if l.strip().startswith(LT + "wire") else l for l in lines]
    extra = []
    for new, ((x1, y1, x2, y2), (sx, sy), (lx, ly), just) in BUS_SPLIT.items():
        i = find_wire(lines, x1, y1, x2, y2)
        del lines[i]
        extra += [wire_line(x1, y1, sx, sy, new), wire_line(sx, sy, x2, y2, new), wire_line(sx, sy, lx, ly, new),
                  f"  {LT}net ({lx},{ly}) 1 {just} 0 \"{new}\"{GT}", f"  {LT}junction ({sx},{sy}){GT}"]
    # 4. sheet texts: the PWM comment and the run length
    for i, l in enumerate(lines):
        if "50KHz Switches, 180 degrees out of phase" in l:
            lines[i] = l.replace("50KHz Switches, 180 degrees out of phase",
                                 "PWM from the control block (bottom of the sheet): 200 kHz, legs 180 deg apart, Tdead dead time")
        elif l.strip().startswith(LT + "text") and ".tran 0.3" in l:
            lines[i] = l.replace(".tran 0.3", ".tran 20m")
    # 5. append the control block before the closing guillemet of the sheet
    assert lines[-1] == GT, lines[-3:]
    body = body_lines(control_block())
    lines = lines[:-1] + extra + body + [GT, ""]
    open(DST, "wb").write(raw[:4] + eol.join(lines).encode(ENC))
    print(f"wrote {DST} ({len(lines)} lines; +{len(body)} control records)")


if __name__ == "__main__":
    main()
