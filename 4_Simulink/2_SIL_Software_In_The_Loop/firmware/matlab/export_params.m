function export_params()
%EXPORT_PARAMS  Generate firmware/core/params.h from the authoritative gains.
%
%   Computes Mp = M*Kp_ratio and Minv = inv(M) in DOUBLE precision, rounds
%   every constant to float32, and writes firmware/core/params.h. Run from
%   anywhere; the output path is resolved relative to this file.
%
%   The M matrix and all thresholds below are copied verbatim from the three
%   MATLAB Function blocks (shuffler_string_ctrl / _supervisor / _mppt) -
%   those blocks are the AUTHORITATIVE source. After any retuning: update the
%   constants here (and in the blocks), bump PARAMS_VERSION, re-run this
%   script, then re-run the C test suite.
%
%   NOTE: the checked-in params.h was produced by an equivalent double-
%   precision computation (numpy/LAPACK inv). Regenerating here may flip a
%   last-digit ulp in a few Minv entries (different inv() rounding) - that is
%   expected, harmless (tolerances are 1e-3/1e-2), and this script's output
%   then becomes the authoritative file.

VERSION = 'sps-params-1.0.0';

%% ---- authoritative constants (from shuffler_string_ctrl.m et al.) ------
M = [ -12.798383   0.000000  -0.000000  -0.000000   1.043947   0.000000;
       -0.132666 -12.627108   0.000000  -1.014057   1.021695   1.025829;
       -0.130486  -0.200085 -12.492219  -1.001002   0.000612   1.002715;
        0.000000   0.000000   0.000000  -1.945483   0.000000   0.000000;
       -0.000000  -0.000000  -0.000000  -0.000000  -2.061583  -0.000000;
       -0.000000  -0.000000  -0.000000  -0.000000   0.000000  -2.022595 ];
kp = [1.58e-4, 1.58e-4, 1.58e-4, 1.08e-4, 1.08e-4, 1.08e-4];

CTRL_TS = 50e-6;  CTRL_DMIN = 0.05;  CTRL_DMAX = 0.95;  FC = 2000;
A = 2*pi*FC*CTRL_TS / (1 + 2*pi*FC*CTRL_TS);

SUP_TS3 = 1e-3;  SUP_TF = 5e-3;  SUP_I_RATED = 10;
SUP_S_HI = 0.90;  SUP_S_LO = 0.70;
SUP_KB = 60;  SUP_KREL = 6;  SUP_BMAX = 4;  SUP_RVMAX = 30;

MPPT_TS = 1e-3;  MPPT_TP = 0.02;
MPPT_IREF0 = 12;  MPPT_IMIN = 5;  MPPT_IMAX = 14.5;
MPPT_DB = 1.0;  MPPT_KA = 0.01;
MPPT_SMIN = 0.05;  MPPT_SMAX = 1.0;  MPPT_S0 = 0.25;  MPPT_BTOL = 1e-3;

%% ---- derived (double precision) ----------------------------------------
Mp   = M * diag(kp);
Minv = inv(M);
MPPT_N      = round(MPPT_TP / MPPT_TS);
STACK_DECIM = round(SUP_TS3 / CTRL_TS);
SUP_ALPHA   = SUP_TS3 / SUP_TF;

errI = max(max(abs(Minv*M - eye(6))));
fprintf('max |Minv*M - I| = %.3e\n', errI);
assert(errI < 1e-12, 'inv(M) sanity check failed');

%% ---- emit ---------------------------------------------------------------
here = fileparts(mfilename('fullpath'));
dest = fullfile(here, '..', 'core', 'params.h');
fid  = fopen(dest, 'w');     % binary mode: LF line endings on all platforms
assert(fid > 0, 'cannot open %s for writing', dest);
cu = onCleanup(@() fclose(fid));

fprintf(fid, '/*\n');
fprintf(fid, ' * params.h - power-shuffler control stack constants (GENERATED FILE)\n');
fprintf(fid, ' *\n');
fprintf(fid, ' * Generated by firmware/matlab/export_params.m. DO NOT EDIT BY HAND.\n');
fprintf(fid, ' * Mp = M*Kp_ratio and Minv = inv(M) are computed offline in DOUBLE\n');
fprintf(fid, ' * precision and rounded to float32 here. Every constant is a float32\n');
fprintf(fid, ' * literal (''f'' suffix) so host, ARM and AVR builds compute identically.\n');
fprintf(fid, ' */\n');
fprintf(fid, '#ifndef SHUFFLER_PARAMS_H\n#define SHUFFLER_PARAMS_H\n\n');
fprintf(fid, '#define PARAMS_VERSION "%s"\n\n', VERSION);

fprintf(fid, '/* ---------------- inner controller (50 us tick) ---------------- */\n');
sca(fid, 'CTRL_TS',   CTRL_TS,   '[s] controller period');
sca(fid, 'CTRL_DMIN', CTRL_DMIN, 'duty clamp low');
sca(fid, 'CTRL_DMAX', CTRL_DMAX, 'duty clamp high');
sca(fid, 'CTRL_A',    A,         'meas LPF coeff: 2*pi*fc*Ts/(1+2*pi*fc*Ts), fc = 2000 Hz');
fprintf(fid, '\n/* plant decoupling matrix M (row-major 6x6) */\n');
mat(fid, 'CTRL_M_INIT', M);
fprintf(fid, '\n/* Mp = M * diag(Kp_ratio), Kp_ratio = [1.58e-4 x3, 1.08e-4 x3] */\n');
mat(fid, 'CTRL_MP_INIT', Mp);
fprintf(fid, '\n/* Minv = inv(M), double-precision inverse rounded to float32 */\n');
mat(fid, 'CTRL_MINV_INIT', Minv);

fprintf(fid, '\n/* ---------------- supervisor / feasibility governor (1 ms tick) ---------------- */\n');
sca(fid, 'SUP_TS3',     SUP_TS3,     '[s] supervisor period');
sca(fid, 'SUP_TF',      SUP_TF,      '[s] measurement filter time constant');
sca(fid, 'SUP_ALPHA',   SUP_ALPHA,   'Ts3/TF');
sca(fid, 'SUP_I_RATED', SUP_I_RATED, '[A] shuffler current rating');
sca(fid, 'SUP_S_HI',    SUP_S_HI,    'stress: governor engage threshold');
sca(fid, 'SUP_S_LO',    SUP_S_LO,    'stress: governor release threshold');
sca(fid, 'SUP_KB',      SUP_KB,      '[1/s] beta attack rate');
sca(fid, 'SUP_KREL',    SUP_KREL,    '[1/s] beta release rate');
sca(fid, 'SUP_BMAX',    SUP_BMAX,    'beta ceiling');
sca(fid, 'SUP_RVMAX',   SUP_RVMAX,   '[V] rv clamp');

fprintf(fid, '\n/* ---------------- MPPT, adaptive-step P&O (1 ms tick) ---------------- */\n');
sca(fid, 'MPPT_TS',    MPPT_TS,    '[s] MPPT period');
sca(fid, 'MPPT_TP',    MPPT_TP,    '[s] perturb / averaging window');
fprintf(fid, '#define MPPT_N         %d /* window length = round(TP/Ts) [ticks] */\n', MPPT_N);
sca(fid, 'MPPT_IREF0', MPPT_IREF0, '[A] initial string current reference');
sca(fid, 'MPPT_IMIN',  MPPT_IMIN,  '[A] Iref clamp low');
sca(fid, 'MPPT_IMAX',  MPPT_IMAX,  '[A] Iref clamp high');
sca(fid, 'MPPT_DB',    MPPT_DB,    '[W] power deadband');
sca(fid, 'MPPT_KA',    MPPT_KA,    '[A/W] adaptive step gain');
sca(fid, 'MPPT_SMIN',  MPPT_SMIN,  '[A] step clamp low');
sca(fid, 'MPPT_SMAX',  MPPT_SMAX,  '[A] step clamp high');
sca(fid, 'MPPT_S0',    MPPT_S0,    '[A] boot perturb step');
sca(fid, 'MPPT_BTOL',  MPPT_BTOL,  'beta change tolerance (governor-active latch)');

fprintf(fid, '\n/* ---------------- stack scheduling / interconnect ---------------- */\n');
fprintf(fid, '#define STACK_DECIM    %d /* controller ticks per supervisor/MPPT tick */\n', ...
        STACK_DECIM);
sca(fid, 'STACK_RV_DLY_IC', 0, 'rv unit-delay initial condition');
fprintf(fid, '#define STACK_IREF_DLY_IC MPPT_IREF0 /* Iref unit-delay initial condition */\n');

fprintf(fid, '\n#endif /* SHUFFLER_PARAMS_H */\n');
fprintf('wrote %s\n', dest);
end

function s = fmtf(x)
%FMTF  Format a value as a float32 C literal (keep in sync with gen_params.py).
s = sprintf('%.9g', double(single(x)));
if ~any(ismember(s, '.eE'))
    s = [s '.0'];
end
s = [s 'f'];
end

function sca(fid, name, x, comment)
fprintf(fid, '#define %-14s %s /* %s */\n', name, fmtf(x), comment);
end

function mat(fid, name, m)
fprintf(fid, '#define %s { \\\n', name);
for i = 1:6
    row = strjoin(arrayfun(@fmtf, m(i, :), 'UniformOutput', false), ', ');
    if i < 6
        fprintf(fid, '    { %s }, \\\n', row);
    else
        fprintf(fid, '    { %s } }\n', row);
    end
end
end
