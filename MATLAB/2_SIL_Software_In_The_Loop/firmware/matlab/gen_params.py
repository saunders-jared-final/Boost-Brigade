#!/usr/bin/env python3
"""Mirror of export_params.m - generates firmware/core/params.h without MATLAB.

Keep this file's emission logic in exact sync with export_params.m. The MATLAB
script is the authoritative generator (run it after any retuning); this mirror
produced the initially checked-in params.h and exists so the C tree can be
regenerated and tested without a MATLAB license. numpy's inv() goes through
the same LAPACK route as MATLAB's, so outputs agree (at worst a last-digit
ulp on a few Minv entries).

Usage: python3 gen_params.py [dest]   (default dest: ../core/params.h)
"""
import math
import os
import struct
import sys

import numpy as np

# ---- authoritative constants (from shuffler_string_ctrl.m et al.) ----------
M = np.array([
    [-12.798383,   0.000000,  -0.000000,  -0.000000,   1.043947,   0.000000],
    [ -0.132666, -12.627108,   0.000000,  -1.014057,   1.021695,   1.025829],
    [ -0.130486,  -0.200085, -12.492219,  -1.001002,   0.000612,   1.002715],
    [  0.000000,   0.000000,   0.000000,  -1.945483,   0.000000,   0.000000],
    [ -0.000000,  -0.000000,  -0.000000,  -0.000000,  -2.061583,  -0.000000],
    [ -0.000000,  -0.000000,  -0.000000,  -0.000000,   0.000000,  -2.022595]])
kp = np.array([1.58e-4, 1.58e-4, 1.58e-4, 1.08e-4, 1.08e-4, 1.08e-4])

CTRL_TS = 50e-6
CTRL_DMIN, CTRL_DMAX = 0.05, 0.95
FC = 2000.0
A = (2.0 * math.pi * FC * CTRL_TS) / (1.0 + 2.0 * math.pi * FC * CTRL_TS)

SUP_TS3, SUP_TF = 1e-3, 5e-3
SUP_I_RATED = 10.0
SUP_S_HI, SUP_S_LO = 0.90, 0.70
SUP_KB, SUP_KREL, SUP_BMAX, SUP_RVMAX = 60.0, 6.0, 4.0, 30.0

MPPT_TS, MPPT_TP = 1e-3, 0.02
MPPT_IREF0, MPPT_IMIN, MPPT_IMAX = 12.0, 5.0, 14.5
MPPT_DB, MPPT_KA = 1.0, 0.01
MPPT_SMIN, MPPT_SMAX, MPPT_S0, MPPT_BTOL = 0.05, 1.0, 0.25, 1e-3

VERSION = "sps-params-1.0.0"

# ---- derived (double precision) --------------------------------------------
Mp = M @ np.diag(kp)
Minv = np.linalg.inv(M)
MPPT_N = round(MPPT_TP / MPPT_TS)
STACK_DECIM = round(SUP_TS3 / CTRL_TS)
SUP_ALPHA = SUP_TS3 / SUP_TF

err = np.max(np.abs(Minv @ M - np.eye(6)))
print(f"max |Minv*M - I| = {err:.3e}", file=sys.stderr)
assert err < 1e-12


def f32(x: float) -> float:
    """Round a double to the nearest float32 (returned as a double)."""
    return struct.unpack("f", struct.pack("f", x))[0]


def fmtf(x: float) -> str:
    """Format a value as a float32 C literal (matches fmtf() in export_params.m)."""
    s = "%.9g" % f32(x)
    if not any(c in s for c in ".eE"):
        s += ".0"
    return s + "f"


def emit_scalar(name: str, x: float, comment: str = "") -> str:
    c = f" /* {comment} */" if comment else ""
    return f"#define {name:<14} {fmtf(x)}{c}\n"


def emit_matrix(name: str, m: np.ndarray) -> str:
    lines = [f"#define {name} {{ \\\n"]
    for i in range(6):
        row = ", ".join(fmtf(v) for v in m[i])
        tail = " }, \\\n" if i < 5 else " } }\n"
        lines.append("    { " + row + tail)
    return "".join(lines)


out = []
out.append("/*\n")
out.append(" * params.h - power-shuffler control stack constants (GENERATED FILE)\n")
out.append(" *\n")
out.append(" * Generated by firmware/matlab/export_params.m. DO NOT EDIT BY HAND.\n")
out.append(" * Mp = M*Kp_ratio and Minv = inv(M) are computed offline in DOUBLE\n")
out.append(" * precision and rounded to float32 here. Every constant is a float32\n")
out.append(" * literal ('f' suffix) so host, ARM and AVR builds compute identically.\n")
out.append(" */\n")
out.append("#ifndef SHUFFLER_PARAMS_H\n")
out.append("#define SHUFFLER_PARAMS_H\n\n")
out.append(f'#define PARAMS_VERSION "{VERSION}"\n\n')

out.append("/* ---------------- inner controller (50 us tick) ---------------- */\n")
out.append(emit_scalar("CTRL_TS", CTRL_TS, "[s] controller period"))
out.append(emit_scalar("CTRL_DMIN", CTRL_DMIN, "duty clamp low"))
out.append(emit_scalar("CTRL_DMAX", CTRL_DMAX, "duty clamp high"))
out.append(emit_scalar("CTRL_A", A, "meas LPF coeff: 2*pi*fc*Ts/(1+2*pi*fc*Ts), fc = 2000 Hz"))
out.append("\n/* plant decoupling matrix M (row-major 6x6) */\n")
out.append(emit_matrix("CTRL_M_INIT", M))
out.append("\n/* Mp = M * diag(Kp_ratio), Kp_ratio = [1.58e-4 x3, 1.08e-4 x3] */\n")
out.append(emit_matrix("CTRL_MP_INIT", Mp))
out.append("\n/* Minv = inv(M), double-precision inverse rounded to float32 */\n")
out.append(emit_matrix("CTRL_MINV_INIT", Minv))

out.append("\n/* ---------------- supervisor / feasibility governor (1 ms tick) ---------------- */\n")
out.append(emit_scalar("SUP_TS3", SUP_TS3, "[s] supervisor period"))
out.append(emit_scalar("SUP_TF", SUP_TF, "[s] measurement filter time constant"))
out.append(emit_scalar("SUP_ALPHA", SUP_ALPHA, "Ts3/TF"))
out.append(emit_scalar("SUP_I_RATED", SUP_I_RATED, "[A] shuffler current rating"))
out.append(emit_scalar("SUP_S_HI", SUP_S_HI, "stress: governor engage threshold"))
out.append(emit_scalar("SUP_S_LO", SUP_S_LO, "stress: governor release threshold"))
out.append(emit_scalar("SUP_KB", SUP_KB, "[1/s] beta attack rate"))
out.append(emit_scalar("SUP_KREL", SUP_KREL, "[1/s] beta release rate"))
out.append(emit_scalar("SUP_BMAX", SUP_BMAX, "beta ceiling"))
out.append(emit_scalar("SUP_RVMAX", SUP_RVMAX, "[V] rv clamp"))

out.append("\n/* ---------------- MPPT, adaptive-step P&O (1 ms tick) ---------------- */\n")
out.append(emit_scalar("MPPT_TS", MPPT_TS, "[s] MPPT period"))
out.append(emit_scalar("MPPT_TP", MPPT_TP, "[s] perturb / averaging window"))
out.append(f"#define MPPT_N         {MPPT_N} /* window length = round(TP/Ts) [ticks] */\n")
out.append(emit_scalar("MPPT_IREF0", MPPT_IREF0, "[A] initial string current reference"))
out.append(emit_scalar("MPPT_IMIN", MPPT_IMIN, "[A] Iref clamp low"))
out.append(emit_scalar("MPPT_IMAX", MPPT_IMAX, "[A] Iref clamp high"))
out.append(emit_scalar("MPPT_DB", MPPT_DB, "[W] power deadband"))
out.append(emit_scalar("MPPT_KA", MPPT_KA, "[A/W] adaptive step gain"))
out.append(emit_scalar("MPPT_SMIN", MPPT_SMIN, "[A] step clamp low"))
out.append(emit_scalar("MPPT_SMAX", MPPT_SMAX, "[A] step clamp high"))
out.append(emit_scalar("MPPT_S0", MPPT_S0, "[A] boot perturb step"))
out.append(emit_scalar("MPPT_BTOL", MPPT_BTOL, "beta change tolerance (governor-active latch)"))

out.append("\n/* ---------------- stack scheduling / interconnect ---------------- */\n")
out.append(f"#define STACK_DECIM    {STACK_DECIM} /* controller ticks per supervisor/MPPT tick */\n")
out.append(emit_scalar("STACK_RV_DLY_IC", 0.0, "rv unit-delay initial condition"))
out.append("#define STACK_IREF_DLY_IC MPPT_IREF0 /* Iref unit-delay initial condition */\n")

out.append("\n#endif /* SHUFFLER_PARAMS_H */\n")

here = os.path.dirname(os.path.abspath(__file__))
dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "core", "params.h")
with open(dest, "w", newline="\n") as f:
    f.write("".join(out))
print(f"wrote {dest}", file=sys.stderr)
